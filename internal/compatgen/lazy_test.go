package compatgen

import (
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// A long top-level definition becomes a stand-in and a cold file; a hot,
// short, nested or redirected one stays; one name defined differently in
// two files is refused.
func TestLazify(t *testing.T) {
	long := strings.Repeat("    : filler\n", 40)
	src := "#!/usr/bin/env bash\n# doc\ncold_one() {\n" + long + "}\nshort() { :; }\n__gash_call() {\n" + long + "}\n" +
		"if true; then\n    nested() {\n" + long + "    }\nfi\nredir() {\n" + long + "} 2>/dev/null\n"
	cold := map[string]coldDef{}
	out, err := lazify("x.sh", []byte(src), cold)
	require.NoError(t, err)
	require.Len(t, cold, 1)
	c := cold["cold_one"]
	require.Equal(t, "cold_one() {\n"+long+"}", string(c.def))
	require.Contains(t, string(out), "# doc\ncold_one() { __gash_cold cold_one "+c.hash+` && "${FUNCNAME[0]}" "$@"; }`+"\nshort() { :; }\n__gash_call() {\n")
	require.Contains(t, string(out), "    nested() {\n")
	require.Contains(t, string(out), "redir() {\n")

	_, err = lazify("y.sh", []byte(src), cold)
	require.NoError(t, err) // the same definition again
	_, err = lazify("z.sh", []byte("cold_one() {\n"+long+": other\n}\n"), cold)
	require.ErrorContains(t, err, "cold_one is defined differently in x.sh")

	f := coldFiles(cold)
	require.Len(t, f, 1)
	require.Equal(t, ColdDir+"cold_one.sh", f[0].Path)
	require.Equal(t, "# shellcheck shell=bash\n# Generated by `gash __compat generate` from x.sh: do not edit. "+c.hash+"\n"+string(c.def)+"\n", string(f[0].Data))
}
