// packAreas place the alias packs (lib/aliases/<pack>.sh).
var packAreas = map[string]string{
	"colors": "shell", "navigation": "shell", "safety": "shell", "general": "shell",
	"git": "git", "docker": "docker", "php": "runtimes",
}

// packOrder is the load order of the packs.
var packOrder = []string{"colors", "navigation", "safety", "general", "git", "docker", "php"}

// packNotes explain what the alias table of a pack cannot.
var packNotes = map[string]string{
	"colors":     "`grep` gets `--color=auto` when the system's grep supports it.",
	"navigation": "`ls`, `ll`, `la`, `l`, `lash`, `sl`, `dir` and `vdir` also get the color option of the system's `ls` (`--color=auto` on GNU, `-G` on BSD and macOS) when it has one.",
	"safety":     "Interactive and verbose forms of the commands that overwrite or delete. On by default: `GASH_SAFETY_ALIASES=0` in `~/.gash_env` turns the pack off (see [configuration](../configuration.md)).",
	"general":    "With `GASH_REPLACE_TOOLS=1`, Gash also aliases standard commands to their richer replacements when those are installed: see [configuration](../configuration.md).",
	"git":        "Loaded when `git` is on PATH. The first six entries are log functions (`gl --help` lists their options). An alias that would hide an installed program of the same name is skipped (`gs` when Ghostscript is installed).",
	"docker":     "Loaded when `docker` is on PATH.",
	"php":        "Loaded when `php` is on PATH. `phpX.Y` stands for the absolute path of that binary followed by `-d allow_url_fopen=1 -d memory_limit=2048M`.",
}

// groups split the functions of an area into sections by help topic, for
// the areas that hold more than one family.
var groups = map[string][]struct{ Topic, Title string }{
	"agents": {{"llm", "Read-only functions (llm_*)"}, {"agent", "Write functions (agent_*)"}},
}

// HelpFunc returns the --help output of a gash command line ("hte",
// "site", "create"), as `gash hte site create --help` prints it.
type HelpFunc func(args ...string) string

// Reference renders docs/<area>/reference.md: the functions of the area
// from the help registry, its alias packs, and its gash commands with every
// subcommand.
func Reference(a Area, help HelpFunc) string {
	var b strings.Builder
	w := func(s ...string) {
		for _, l := range s {
			b.WriteString(l + "\n")
		}
	}
	w("<!-- Generated by go test ./internal/docgen -update: do not edit. -->",
		"",
		"# "+a.Title+": reference",
		"",
		a.Summary+" The guide is [README.md](README.md); this page lists every function, alias and command, as their own help prints it (`gash_help NAME`, `gash COMMAND --help`).")

	fns := FunctionsOf(a.Key)
	if len(fns) > 0 {
		if gs, ok := groups[a.Key]; ok {
			for _, g := range gs {
				var sub []registry.Function
				for _, f := range fns {
					if f.Topic == g.Topic {
						sub = append(sub, f)
					}
				}
				w("", "## "+g.Title, "")
				functionTable(w, sub)
			}
		} else {
			w("", "## Functions", "")
			functionTable(w, fns)
		}
		for _, f := range fns {
			function(w, f)
		}
	}

	first := true
	for _, pack := range packOrder {
		if packAreas[pack] != a.Key {
			continue
		}
		if first {
			w("", "## Aliases", "", "Defined in interactive shells, in packs. The Defined column says when an alias exists; empty means always.")
			first = false
		}
		w("", "### The "+pack+" pack", "")
		if n := packNotes[pack]; n != "" {
			w(n, "")
		}
		w("| Alias | Runs | Defined |", "|---|---|---|")
		defined := map[string]bool{}
		for _, al := range registry.Aliases() {
			if al.Pack == pack {
				defined[al.Name] = true
			}
		}
		for _, al := range registry.CardAliases(pack) {
			name, runs := "`"+al.Name+"`", code(al.Value)
			if al.Each != "" {
				name += " (`" + al.Each + "` followed by the version digits)"
			} else if !defined[al.Name] {
				// A shell function of the pack: the card describes it.
				runs = cell(al.Value)
			}
			w("| " + name + " | " + runs + " | " + cell(al.Condition) + " |")
		}
	}

	if len(a.Commands) > 0 && help != nil {
		w("", "## Commands")
		for _, c := range a.Commands {
			command(w, help, []string{c})
		}
	}
	return b.String()
}

func functionTable(w func(...string), fns []registry.Function) {
	w("| Function | Alias | Description |", "|---|---|---|")
	for _, f := range fns {
		alias := ""
		if len(f.Aliases) > 0 {
			alias = "`" + strings.Join(f.Aliases, "`, `") + "`"
		}
		w("| [`" + f.Name + "`](#" + anchor(f.Name) + ") | " + alias + " | " + cell(f.Help.Short) + " |")
	}
}

// function renders one function: its short description, aliases, the
// commands it replaces, each help section, and its see-also links.
func function(w func(...string), f registry.Function) {
	w("", "### "+f.Name, "", strings.TrimSuffix(f.Help.Short, ".")+".")
	if len(f.Aliases) > 0 {
		w("", "Alias: `"+strings.Join(f.Aliases, "`, `")+"`")
	}
	if routes := registry.RoutesOf(f.Name); len(routes) > 0 {
		w("", "Replaces:", "")
		for _, r := range routes {
			line := "- " + code(r.Shape)
			if r.Use != r.Fn {
				line += " (" + code(r.Use) + ")"
			}
			w(line)
		}
	}
	for _, sec := range helpSections(f.Help.Body) {
		fence := "text"
		if sec.title == "EXAMPLES" {
			fence = "bash"
		}
		w("", "#### "+titleCase(sec.title), "", "```"+fence, sec.text, "```")
	}
	if f.Help.SeeAlso != "" {
		var links []string
		for _, name := range strings.Fields(f.Help.SeeAlso) {
			links = append(links, link(name))
		}
		w("", "See also: "+strings.Join(links, ", "))
	}
}

// link is a see-also entry: a link to the function's section in the
// reference of its area, plain code when it is not a documented function.
func link(name string) string {
	for _, f := range registry.Functions() {
		if f.Name != name || !f.HasHelp {
			continue
		}
		area := AreaOf(f)
		if area == "" {
			break
		}
		return "[`" + name + "`](../" + area + "/reference.md#" + anchor(name) + ")"
	}
	return "`" + name + "`"
}

// command renders a gash command and, recursively, its subcommands.
func command(w func(...string), help HelpFunc, path []string) {
	out := strings.TrimRight(help(path...), "\n")
	w("", "### gash "+strings.Join(path, " "), "", "```text", out, "```")
	for _, sub := range subcommands(out) {
		command(w, help, append(append([]string{}, path...), sub))
	}
}

// subcommands are the names under "Available Commands:" in a cobra help
// text, without help and completion.
func subcommands(help string) []string {
	var out []string
	in := false
	for _, line := range strings.Split(help, "\n") {
		switch {
		case strings.HasPrefix(line, "Available Commands:"):
			in = true
		case in && strings.HasPrefix(line, "  "):
			name := strings.Fields(line)[0]
			if name != "help" && name != "completion" {
				out = append(out, name)
			}
		case in:
			in = false
		}
	}
	return out
}

type helpSection struct{ title, text string }

// helpSections splits a help body at its unindented upper-case headings;
// the section text loses its two-space indent and its trailing blank lines.
func helpSections(body string) []helpSection {
	var out []helpSection
	for _, line := range strings.Split(body, "\n") {
		if line != "" && line == strings.ToUpper(line) && !strings.HasPrefix(line, " ") {
			out = append(out, helpSection{title: line})
			continue
		}
		if len(out) == 0 {
			continue
		}
		s := &out[len(out)-1]
		if s.text != "" || line != "" {
			s.text += strings.TrimPrefix(line, "  ") + "\n"
		}
	}
	for i := range out {
		out[i].text = strings.TrimRight(out[i].text, "\n")
	}
	return out
}

func titleCase(s string) string {
	s = strings.ToLower(s)
	return strings.ToUpper(s[:1]) + s[1:]
}

// code is s as inline code in a table cell: pipes escaped, a fence longer
// than any backtick run inside.
func code(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	fence := "`"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	if fence != "`" || strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		return fence + " " + s + " " + fence
	}
	return fence + s + fence
}

// cell is text for a table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
