// mountinfoWSL2 is /proc/self/mountinfo of a WSL 2 distribution (Ubuntu
// 24.04, WSL 2.6), cut to the lines that matter: the root, two Windows
// drives over 9p (C with the metadata option), the WSLg share and a tmpfs.
const mountinfoWSL2 = `62 1 8:32 / / rw,relatime - ext4 /dev/sdc rw,discard,errors=remount-ro,data=ordered
71 62 0:30 / /mnt/wslg rw,relatime shared:1 - tmpfs none rw
82 62 0:52 / /mnt/c rw,noatime - 9p C:\134 rw,aname=drvfs;path=C:\;uid=1000;gid=1000;metadata;symlinkroot=/mnt/,mmap,access=client,msize=65536,trans=fd,rfd=5,wfd=5
83 62 0:53 / /mnt/d rw,noatime - 9p D:\134 rw,aname=drvfs;path=D:\;uid=1000;gid=1000;symlinkroot=/mnt/,mmap,access=client,msize=65536,trans=fd,rfd=5,wfd=5
90 62 0:60 / /run/user rw,nosuid,nodev - tmpfs tmpfs rw,mode=755
`

// mountinfoRootSlash is the same with [automount] root = / (drives on /c).
const mountinfoRootSlash = `82 62 0:52 / /c rw,noatime - 9p C:\134 rw,aname=drvfs;path=C:\;uid=1000;gid=1000;symlinkroot=/,mmap,access=client,msize=65536,trans=fd,rfd=5,wfd=5
`

type tree map[string]string

func sysroot(t *testing.T, files tree) platform.Sysroot {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if body == "<dir>" {
			if err := os.MkdirAll(p, 0o755); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if body == "<socket>" {
			l, err := net.Listen("unix", p)
			if err != nil {
				t.Skip("unix socket:", err)
			}
			t.Cleanup(func() { l.Close() })
			continue
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	sr, err := platform.NewSysroot(dir)
	if err != nil {
		t.Fatal(err)
	}
	return sr
}

func env(m map[string]string) func(string) string { return func(k string) string { return m[k] } }

func TestDetect_WSL2(t *testing.T) {
	sr := sysroot(t, tree{
		"proc/sys/kernel/osrelease":          "6.6.87.2-microsoft-standard-WSL2\n",
		"proc/version":                       "Linux version 6.6.87.2-microsoft-standard-WSL2 (root@x) ...\n",
		"proc/sys/fs/binfmt_misc/WSLInterop": "enabled\ninterpreter /init\nflags: PF\noffset 0\nmagic 4d5a\n",
		"proc/self/mountinfo":                mountinfoWSL2,
		"proc/1/comm":                        "systemd\n",
		"proc/412":                           "<dir>",
		"proc/77":                            "<dir>",
		"run/WSL/412_interop":                "<socket>",
		"run/WSL/77_interop":                 "<socket>",
		"run/WSL/9999_interop":               "<socket>", // its process is gone
		"sys/class/net/eth0":                 "<dir>",
		"etc/resolv.conf":                    "# This file was automatically generated by WSL.\nnameserver 10.255.255.254\n",
		"mnt/wslg":                           "<dir>",
	})
	f := Detect(sr, env(map[string]string{
		"WSL_DISTRO_NAME": "Ubuntu-24.04",
		"WSL_INTEROP":     "/run/WSL/5_interop", // stale: tmux reattached
		"PATH":            "/usr/bin:/bin:/mnt/c/WINDOWS/system32:/mnt/c/Users/me/AppData/Local/Microsoft/WindowsApps",
	}))
	if !f.WSL || f.Version != 2 || f.Distro != "Ubuntu-24.04" {
		t.Fatalf("facts = %+v", f)
	}
	if !f.Interop.Registered || !f.Interop.Enabled || !f.Interop.Stale || f.Interop.Socket != "/run/WSL/412_interop" {
		t.Errorf("interop = %+v", f.Interop)
	}
	if f.AutomountRoot != "/mnt/" || len(f.Drives) != 2 || f.Drives[0].Letter != "C" || !f.Drives[0].Metadata || f.Drives[1].Metadata {
		t.Errorf("drives = %s %+v", f.AutomountRoot, f.Drives)
	}
	if !f.Systemd || !f.WindowsPath || f.Networking != "nat" || !f.DNSTunneling || !f.WSLg {
		t.Errorf("facts = %+v", f)
	}
}

