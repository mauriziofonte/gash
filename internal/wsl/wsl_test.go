func TestDetect_RootSlashAndMirrored(t *testing.T) {
	sr := sysroot(t, tree{
		"proc/sys/kernel/osrelease": "6.6.87.2-microsoft-standard-WSL2\n",
		"proc/self/mountinfo":       mountinfoRootSlash,
		"sys/class/net/loopback0":   "<dir>",
		"sys/class/net/eth0":        "<dir>",
	})
	f := Detect(sr, env(nil))
	if f.AutomountRoot != "/" || f.Networking != "mirrored" {
		t.Errorf("facts = %+v", f)
	}
	if got, err := f.ToWindows("/c/Users/me", FormWindows); err != nil || got != `C:\Users\me` {
		t.Errorf("ToWindows = %q, %v", got, err)
	}
	if got, err := f.ToLinux(`C:\Users\me`); err != nil || got != "/c/Users/me" {
		t.Errorf("ToLinux = %q, %v", got, err)
	}
	if got, err := f.ToLinux(`E:\x`); err != nil || got != "/e/x" {
		t.Errorf("unmounted drive = %q, %v", got, err)
	}
}

func TestPaths(t *testing.T) {
	f := Facts{WSL: true, Distro: "Ubuntu", AutomountRoot: "/mnt/",
		Drives: []Drive{{Letter: "C", Mount: "/mnt/c"}, {Letter: "D", Mount: "/mnt/d"}}}
	for _, c := range []struct{ in, form, want string }{
		{"/mnt/c/Users/me/file.txt", FormWindows, `C:\Users\me\file.txt`},
		{"/mnt/c", FormWindows, `C:\`},
		{"/mnt/c/", FormMixed, `C:/`},
		{"/mnt/d/a b/../c", FormMixed, `D:/c`},
		{"/home/me/src", FormWindows, `\\wsl.localhost\Ubuntu\home\me\src`},
		{"/", FormWindows, `\\wsl.localhost\Ubuntu\`},
		{"/home/me", FormMixed, `//wsl.localhost/Ubuntu/home/me`},
		{"/mnt/cc/x", FormWindows, `\\wsl.localhost\Ubuntu\mnt\cc\x`},
	} {
		if got, err := f.ToWindows(c.in, c.form); err != nil || got != c.want {
			t.Errorf("ToWindows(%q, %s) = %q, %v; want %q", c.in, c.form, got, err, c.want)
		}
	}
	for _, c := range []struct{ in, want string }{
		{`C:\Users\me\file.txt`, "/mnt/c/Users/me/file.txt"},
		{`c:/Users`, "/mnt/c/Users"},
		{`C:`, "/mnt/c"},
		{`C:\`, "/mnt/c"},
		{`\\wsl.localhost\Ubuntu\home\me`, "/home/me"},
		{`\\WSL$\ubuntu\etc\..\home`, "/home"},
		{`dir\file`, "dir/file"},
	} {
		if got, err := f.ToLinux(c.in); err != nil || got != c.want {
			t.Errorf("ToLinux(%q) = %q, %v; want %q", c.in, got, err, c.want)
		}
	}
	for _, in := range []string{`\\server\share\x`, `\\wsl.localhost\Debian\x`, `\Windows`} {
		if _, err := f.ToLinux(in); err != ErrNotMapped {
			t.Errorf("ToLinux(%q) err = %v, want ErrNotMapped", in, err)
		}
	}
	if _, err := (Facts{}).ToWindows("/home", FormWindows); err != ErrNoDistro {
		t.Errorf("no distro: %v", err)
	}
}

func TestINI(t *testing.T) {
	ini := ParseINI(DecodeText([]byte("\xef\xbb\xbf# comment\n[boot]\nsystemd = true  # on\n[Automount]\nOptions = \"metadata,umask=22\"\nroot=/\nbogus line\n[interop]\nappendWindowsPath=false\r\n[x]\nfoo=1\n")))
	if v, _ := ini.Get("BOOT", "Systemd"); v != "true" {
		t.Errorf("systemd = %q", v)
	}
	if v, _ := ini.Get("automount", "options"); v != "metadata,umask=22" {
		t.Errorf("options = %q", v)
	}
	if len(ini.Bad) != 1 || ini.Bad[0].Line != 7 {
		t.Errorf("bad = %+v", ini.Bad)
	}
	known, unknown := Resolve("wsl.conf", ini)
	got := map[string]Effective{}
	for _, e := range known {
		got[e.Section+"."+e.Key] = e
	}
	if e := got["interop.appendWindowsPath"]; e.Value != "false" || e.Source != "file" || e.Line != 9 {
		t.Errorf("appendWindowsPath = %+v", e)
	}
	if e := got["network.generateHosts"]; e.Value != "true" || e.Source != "default" {
		t.Errorf("generateHosts = %+v", e)
	}
	if len(unknown) != 1 || unknown[0].Key != "x.foo" {
		t.Errorf("unknown = %+v", unknown)
	}
	// Notepad's UTF-16 LE with a BOM.
	u16 := []byte{0xff, 0xfe}
	for _, r := range "[wsl2]\r\nmemory=8GB\r\n" {
		u16 = append(u16, byte(r), 0)
	}
	if v, _ := ParseINI(DecodeText(u16)).Get("wsl2", "memory"); v != "8GB" {
		t.Errorf("utf-16 memory = %q", v)
	}
}

