// Class is the legacy format of a vhost file (design/hte.md section 10).
type Class string

// The classes of the migrate table.
const (
	ClassV1           Class = "V1"            // hte-cli 1.0.x
	ClassV1Fixed      Class = "V1-fixed"      // V1 after hte-cli fix
	ClassV2           Class = "V2"            // hte-cli 1.1.x
	ClassBrokenBypass Class = "Broken-bypass" // the force block fix repairs
	ClassMalformed    Class = "Malformed"     // marker present, domain or socket missing
	ClassRaw          Class = "Raw"           // no marker
)

// The hte-cli markers and force comments, matched as substrings of the
// file as hte-cli did (ApacheManager.php:64-67, 89).
const (
	MarkerV1      = "# Auto-generated by the test environment creator"
	MarkerV2      = "# Auto-generated by HTE-Cli"
	ForceComment  = "# Auto-generated Force HTTPS"
	BypassComment = "# Auto-generated Force HTTPS (bypassed for localhost requests)"
)

var (
	// brokenRE is needsLocalhostBypassFix's test for the Broken-bypass
	// shape: a blank line right after the HTTPS condition.
	brokenRE = lazyre.MustCompile(`RewriteCond\s+%\{HTTPS\}\s+off[ \t]*\n\s*\n`)
	// bypassCondRE is the loopback bypass condition of the force block.
	bypassCondRE = lazyre.MustCompile(`(?m)^[ \t]*RewriteCond[ \t]+%\{REMOTE_ADDR\}[ \t]+!\^127\\\.0\\\.0\\\.1\$[ \t]*$`)
	// activeRuleRE is an uncommented redirect to https:// in a vhost.
	activeRuleRE = lazyre.MustCompile(`(?m)^[ \t]*RewriteRule[ \t]+\S+[ \t]+https://`)
	// socketRE is a legacy FPM socket inside a SetHandler argument:
	// php<X.Y>-fpm-<domain>.sock (hte-cli) or php<X.Y>-fpm.sock (the
	// distro's www pool).
	socketRE = lazyre.MustCompile(`^proxy:unix:((?:/var)?/run/php/php([0-9]+\.[0-9]+)-fpm(-[^/|]*)?\.sock)\|fcgi://localhost/?$`)
	// anySocketRE finds every proxy:unix socket path in a file.
	anySocketRE = lazyre.MustCompile(`proxy:unix:([^|"\s]+)`)
	indexRE     = lazyre.MustCompile(`^([0-9]+)-.*\.conf$`)
)

// Vhost is one classified vhost file.
type Vhost struct {
	Path    string `json:"path"` // system path
	Enabled bool   `json:"enabled"`
	Index   int    `json:"index"` // NNN- prefix of the file name, -1 when none
	Class   Class  `json:"class"`
	Reason  string `json:"reason,omitempty"` // why it is Malformed

	// Facts read from the file. For marked files the domain and PHP
	// version come from the socket (hte-cli's identity); for raw files the
	// domain is the first ServerName.
	Domain           string   `json:"domain,omitempty"` // as written
	PHP              string   `json:"php,omitempty"`
	Socket           string   `json:"socket,omitempty"`
	ServerName       string   `json:"server_name,omitempty"`
	Aliases          []string `json:"aliases,omitempty"`
	Docroot          string   `json:"docroot,omitempty"`
	DocrootRecovered bool     `json:"docroot_recovered,omitempty"` // taken from <Directory> after a truncated DocumentRoot
	HTTPS            bool     `json:"https"`
	CertFile         string   `json:"cert_file,omitempty"`
	KeyFile          string   `json:"key_file,omitempty"`
	Forced           bool     `json:"forced"`
	Bypass           bool     `json:"bypass"`
	Ports            []int    `json:"ports,omitempty"`   // every VirtualHost port, sorted, unique
	Sockets          []string `json:"sockets,omitempty"` // every proxy:unix path
	Warnings         []string `json:"warnings,omitempty"`

	Data []byte    `json:"-"`
	Conf *ConfFile `json:"-"`
}

// Marked reports whether the file carries an hte-cli marker.
func (v Vhost) Marked() bool { return v.Class != ClassRaw }

func fileIndex(p string) int {
	m := indexRE.FindStringSubmatch(path.Base(p))
	if m == nil {
		return -1
	}
	n, err := strconv.Atoi(m[1])
	if err != nil {
		return -1
	}
	return n
}

// Classify parses and classifies one vhost file.
func Classify(p string, data []byte) Vhost {
	text := string(data)
	v := Vhost{Path: p, Index: fileIndex(p), Data: data}
	v1, v2 := strings.Contains(text, MarkerV1), strings.Contains(text, MarkerV2)
	cf, err := ParseConf(data)
	if err == nil {
		v.Conf = cf
		v.readFacts(cf)
	}
	for _, m := range anySocketRE.FindAllStringSubmatch(text, -1) {
		if !slices.Contains(v.Sockets, m[1]) {
			v.Sockets = append(v.Sockets, m[1])
		}
	}
	if !v1 && !v2 {
		v.Class = ClassRaw
		if err != nil {
			v.Reason = "does not parse: " + err.Error()
		}
		return v
	}
	malformed := func(reason string) Vhost {
		v.Class, v.Reason = ClassMalformed, reason
		return v
	}
	if err != nil {
		return malformed("does not parse: " + err.Error())
	}
	if v1 && v2 {
		return malformed("carries both hte-cli markers")
	}
	// Identity: the socket of every SetHandler, all naming the same one.
	var handlers []string
	for _, vh := range cf.Vhosts {
		for _, d := range vh.Find("SetHandler") {
			if len(d.Args) == 1 && strings.HasPrefix(d.Args[0], "proxy:unix:") {
				handlers = append(handlers, d.Args[0])
			}
		}
	}
	if len(handlers) == 0 {
		return malformed("no SetHandler to a PHP-FPM socket")
	}
	for _, h := range handlers[1:] {
		if h != handlers[0] {
			return malformed("the vhosts name different PHP-FPM sockets")
		}
	}
	m := socketRE.FindStringSubmatch(handlers[0])
	switch {
	case m == nil:
		return malformed("the SetHandler socket is not an hte-cli socket: " + handlers[0])
	case m[3] == "":
		return malformed("default socket " + m[1] + " (the distribution's pool, no domain)")
	case m[3] == "-":
		return malformed("empty domain in the socket " + m[1])
	}
	v.Socket, v.PHP, v.Domain = m[1], m[2], m[3][1:]

	forced := strings.Contains(text, ForceComment)
	bypassConds := bypassCondRE.MatchString(text)
	broken := strings.Contains(text, BypassComment) && brokenRE.MatchString(text)
	switch {
	case broken:
		v.Class = ClassBrokenBypass
	case v1 && forced && bypassConds:
		v.Class = ClassV1Fixed
	case v1:
		v.Class = ClassV1
	default:
		v.Class = ClassV2
	}
	// Forced: either force comment (hte-cli's rule, design step 4). The
	// bypass is what the block does, and for an unforced site what the
	// variant would render (D-2: off for V1, on for the others).
	v.Forced = forced
	if forced {
		v.Bypass = bypassConds
		if !activeRuleRE.MatchString(text) {
			v.Warnings = append(v.Warnings, "the force-HTTPS comment is present but no RewriteRule to https:// is active; imported as forced")
		}
	} else {
		v.Bypass = v.Class != ClassV1
	}
	return v
}

// readFacts fills the facts that do not depend on the class.
func (v *Vhost) readFacts(cf *ConfFile) {
	ports := map[int]bool{}
	var docroots, dirs []string
	var docrootWords [][]string
	for _, vh := range cf.Vhosts {
		for _, p := range vh.Ports() {
			ports[p] = true
		}
		for _, d := range vh.Find("ServerName") {
			if v.ServerName == "" && len(d.Args) == 1 {
				v.ServerName = d.Args[0]
			}
		}
		for _, d := range vh.Find("ServerAlias") {
			for _, a := range d.Args {
				if !slices.Contains(v.Aliases, a) {
					v.Aliases = append(v.Aliases, a)
				}
			}
		}
		for _, d := range vh.Find("DocumentRoot") {
			docrootWords = append(docrootWords, d.Args)
			docroots = append(docroots, strings.Join(d.Args, " "))
		}
		for _, d := range vh.Find("Directory") {
			if d.Section && len(d.Path) == 0 {
				dirs = append(dirs, unquoteSectionArg(d.ArgText))
			}
		}
		hasPort443 := slices.Contains(vh.Ports(), 443)
		cert, key := vh.Find("SSLCertificateFile"), vh.Find("SSLCertificateKeyFile")
		if hasPort443 && len(cert) == 1 && len(key) == 1 && len(cert[0].Args) == 1 && len(key[0].Args) == 1 {
			v.HTTPS, v.CertFile, v.KeyFile = true, cert[0].Args[0], key[0].Args[0]
		} else if hasPort443 {
			v.Warnings = append(v.Warnings, "a :443 vhost without both SSLCertificateFile and SSLCertificateKeyFile; imported as HTTP only")
		}
	}
	for p := range ports {
		v.Ports = append(v.Ports, p)
	}
	slices.Sort(v.Ports)
	if len(docroots) == 0 {
		return
	}
	for _, d := range docroots[1:] {
		if d != docroots[0] {
			v.Warnings = append(v.Warnings, "the vhosts have different DocumentRoot values; the first one is used")
			break
		}
	}
	v.Docroot = docroots[0]
	// An unquoted DocumentRoot with spaces is several words: hte-cli read
	// the first one only. The <Directory> section of the same vhost holds
	// the whole path with a trailing slash.
	if len(docrootWords[0]) > 1 {
		for _, dir := range dirs {
			full := strings.TrimSuffix(dir, "/")
			if strings.HasPrefix(full, docrootWords[0][0]+" ") {
				v.Docroot, v.DocrootRecovered = full, true
				break
			}
		}
		if !v.DocrootRecovered {
			v.Docroot = ""
			v.Warnings = append(v.Warnings, "DocumentRoot has several words and no <Directory> recovers it")
		}
	}
}

// unquoteSectionArg returns the raw argument of a section line without
// its surrounding quotes: the path exactly as written, spaces included.
func unquoteSectionArg(s string) string {
	s = strings.TrimSpace(s)
	if len(s) >= 2 && (s[0] == '"' || s[0] == '\'') && s[len(s)-1] == s[0] {
		return s[1 : len(s)-1]
	}
	return s
}
